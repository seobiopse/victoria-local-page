"""Measure how unique each local page's body text is against every other local page.

Run: python check_unique.py   (writes NSW-UNIQUENESS.md)

Body = text between the breadcrumb and the footer (header, nav, footer and schema excluded).
Method: 5-word shingles. For each page:
  unique%  = shingles found on no other page / all shingles on the page
  rare%    = shingles found on 3 or fewer pages in total / all shingles
  max sim  = highest Jaccard similarity with any single other page
Rule of thumb used here: unique% under 25 or max sim over 0.60 gets flagged for more local content.
"""
import os
import re
from collections import defaultdict
from html import unescape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N = 5


def body_text(html):
    a = html.find('<div class="crumbs-section">')
    b = html.find('<footer class="site-footer">')
    seg = html[a:b] if a >= 0 and b > a else html
    seg = re.sub(r'<script.*?</script>', ' ', seg, flags=re.S)
    seg = re.sub(r'<style.*?</style>', ' ', seg, flags=re.S)
    seg = re.sub(r'<[^>]+>', ' ', seg)
    seg = unescape(seg)
    return re.sub(r'\s+', ' ', seg).strip().lower()


def shingles(text):
    w = re.findall(r"[a-z0-9$%.,'-]+", text)
    return {' '.join(w[i:i + N]) for i in range(max(0, len(w) - N + 1))}, len(w)


def main():
    pages = {}
    for dp, _, files in os.walk(os.path.join(ROOT, 'trophies')):
        if 'index.html' in files:
            rel = os.path.relpath(dp, os.path.join(ROOT, 'trophies')).replace(os.sep, '/')
            with open(os.path.join(dp, 'index.html'), encoding='utf-8') as f:
                pages[rel] = shingles(body_text(f.read()))
    count = defaultdict(int)
    for sh, _ in pages.values():
        for x in sh:
            count[x] += 1
    rows = []
    keys = sorted(pages)
    for k in keys:
        sh, wc = pages[k]
        if not sh:
            continue
        uniq = sum(1 for x in sh if count[x] == 1) / len(sh)
        rare = sum(1 for x in sh if count[x] <= 3) / len(sh)
        best, bk = 0.0, ''
        for o in keys:
            if o == k:
                continue
            osh = pages[o][0]
            j = len(sh & osh) / len(sh | osh)
            if j > best:
                best, bk = j, o
        kind = ('state' if k.count('/') == 0 else 'city/town' if k.count('/') == 1 else 'suburb')
        if k.startswith('victoria'):
            kind = {0: 'vic-state', 1: 'vic-town', 2: 'vic-suburb'}[k.count('/')]
            if k == 'victoria/melbourne':
                kind = 'vic-hub'
        rows.append((k, kind, wc, uniq, rare, best, bk))

    def avg(sel, i):
        v = [r[i] for r in rows if sel(r)]
        return sum(v) / len(v) if v else 0

    out = ['# NSW uniqueness check', '',
           'Generated by `check_unique.py`. Body text only (header, nav, footer and schema excluded), 5-word shingles, compared with every other local page including Victoria and Melbourne.', '',
           '| Group | Pages | Avg words | Avg unique % | Avg rare % | Avg max similarity |', '|---|---|---|---|---|---|']
    for label, sel in [('NSW towns', lambda r: r[0].startswith('new-south-wales/') and r[1] == 'city/town' and r[0] != 'new-south-wales/sydney'),
                       ('Sydney suburbs', lambda r: r[1] == 'suburb'),
                       ('Sydney hub + NSW state', lambda r: r[0] in ('new-south-wales', 'new-south-wales/sydney')),
                       ('Victoria (reference)', lambda r: r[1].startswith('vic-'))]:
        n = len([r for r in rows if sel(r)])
        out.append('| %s | %d | %d | %.0f%% | %.0f%% | %.2f |' % (label, n, avg(sel, 2), avg(sel, 3) * 100, avg(sel, 4) * 100, avg(sel, 5)))
    flagged = [r for r in rows if r[0].startswith('new-south-wales') and (r[3] < 0.25 or r[5] > 0.60)]
    out += ['', '## Flagged pages (unique under 25% or max similarity over 0.60)', '']
    if flagged:
        out += ['| Page | Words | Unique % | Rare % | Max sim | Most similar to |', '|---|---|---|---|---|---|']
        for r in sorted(flagged, key=lambda r: r[3]):
            out.append('| %s | %d | %.0f%% | %.0f%% | %.2f | %s |' % (r[0], r[2], r[3] * 100, r[4] * 100, r[5], r[6]))
    else:
        out.append('None.')
    out += ['', '## All NSW pages', '', '| Page | Type | Words | Unique % | Rare % | Max sim | Most similar to |', '|---|---|---|---|---|---|---|']
    for r in rows:
        if r[0].startswith('new-south-wales'):
            out.append('| %s | %s | %d | %.0f%% | %.0f%% | %.2f | %s |' % (r[0], r[1], r[2], r[3] * 100, r[4] * 100, r[5], r[6]))
    with open(os.path.join(ROOT, 'docs', 'nsw', 'NSW-UNIQUENESS.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('\n'.join(out[:14]))
    print('flagged:', len(flagged))

    # ---- Victoria report ----
    vout = ['# Victoria uniqueness check', '',
            'Generated by `check_unique.py`. Body text only (header, nav, footer and schema excluded), 5-word shingles, compared with every other local page including NSW.', '',
            '| Group | Pages | Avg words | Avg unique % | Avg rare % | Avg max similarity |', '|---|---|---|---|---|---|']
    for label, sel in [('Victorian towns', lambda r: r[1] == 'vic-town'),
                       ('Melbourne suburbs', lambda r: r[1] == 'vic-suburb'),
                       ('Victoria state + Melbourne hub', lambda r: r[1] in ('vic-state', 'vic-hub'))]:
        n = len([r for r in rows if sel(r)])
        vout.append('| %s | %d | %d | %.0f%% | %.0f%% | %.2f |' % (label, n, avg(sel, 2), avg(sel, 3) * 100, avg(sel, 4) * 100, avg(sel, 5)))
    vflag = [r for r in rows if r[0].startswith('victoria') and (r[3] < 0.25 or r[5] > 0.60)]
    vout += ['', '## Flagged pages (unique under 25% or max similarity over 0.60)', '']
    if vflag:
        vout += ['| Page | Words | Unique % | Rare % | Max sim | Most similar to |', '|---|---|---|---|---|---|']
        for r in sorted(vflag, key=lambda r: r[3]):
            vout.append('| %s | %d | %.0f%% | %.0f%% | %.2f | %s |' % (r[0], r[2], r[3] * 100, r[4] * 100, r[5], r[6]))
    else:
        vout.append('None.')
    vout += ['', '## All Victoria pages', '', '| Page | Type | Words | Unique % | Rare % | Max sim | Most similar to |', '|---|---|---|---|---|---|---|']
    for r in rows:
        if r[0].startswith('victoria'):
            vout.append('| %s | %s | %d | %.0f%% | %.0f%% | %.2f | %s |' % (r[0], r[1], r[2], r[3] * 100, r[4] * 100, r[5], r[6]))
    os.makedirs(os.path.join(ROOT, 'docs', 'victoria'), exist_ok=True)
    with open(os.path.join(ROOT, 'docs', 'victoria', 'VICTORIA-UNIQUENESS.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(vout) + '\n')
    print('\n'.join(vout[:12]))
    print('VIC flagged:', len(vflag))


if __name__ == '__main__':
    main()
